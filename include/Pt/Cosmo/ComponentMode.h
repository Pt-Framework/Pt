#ifndef COSMO_COMPONENT_MODE_H
#define COSMO_COMPONENT_MODE_H

#include <Pt/Cosmo/Api.h>

namespace Pt {

namespace Cosmo {

/** @brief Component flags.

    Flags controlling component behavior. Components with the
    %AutoStart flag are loaded automatically when the component
    manager starts.

    @ingroup Cosmo-Component
*/
class ComponentMode
{
  public:
    enum Mode
    {
        None = 0,
        AutoStart = 1
    };

  public:
    ComponentMode(Mode m = None)
    : _mode(m)
    {}

    ComponentMode& operator=(Mode m)
    {
      _mode = m;
      return *this;
    }

    bool isAutoStart() const
    { return (_mode & AutoStart) == AutoStart; }

    operator long() const
    {
      return _mode;
    }

  private:
    Mode _mode;
};

} // namespace Cosmo

} // namespace Pt

#endif // include guard
